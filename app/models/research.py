"""Pydantic models for research-related API operations."""

from pydantic import BaseModel, Field


class ResearchRequest(BaseModel):
    """Request body for creating a research request."""

    query: str = Field(
        ...,
        min_length=1,
        max_length=500,
        description="The research question or topic to investigate.",
    )


class ResearchResponse(BaseModel):
    """Response returned after processing a research request."""

    request_id: str = Field(
        ...,
        description="Unique identifier associated with the request.",
    )

    query: str = Field(
        ...,
        description="The original research question or topic.",
    )

    answer: str = Field(
        ...,
        description="The answer generated by the research service.",
    )

    sources: list[str] = Field(
        default_factory=list,
        description="Sources associated with the research result.",
    )